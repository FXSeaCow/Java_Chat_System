-- Java Chat System - PostgreSQL / Supabase schema.
-- Run once on an empty database. PostgreSQL uses UTF-8 on Supabase.
-- The Java backend owns authentication and authorization. RLS below blocks
-- direct access through Supabase's anon/authenticated Data API roles.

BEGIN;

CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

CREATE TABLE public.users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username        VARCHAR(50) NOT NULL,
    email           VARCHAR(255) NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    reset_password_hash VARCHAR(255),
    reset_password_expires_at TIMESTAMPTZ,
    display_name    VARCHAR(100) NOT NULL,
    avatar_url      VARCHAR(2048),
    address         VARCHAR(255),
    date_of_birth   DATE,
    gender          VARCHAR(10),
    role            VARCHAR(20) NOT NULL DEFAULT 'USER',
    status          VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'BLOCKED', 'DELETED')),
    CONSTRAINT ck_users_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER'))
);

-- Enforce one account per email even under concurrent requests and regardless
-- of letter case. AccountRepository also normalizes new addresses to lowercase.
CREATE UNIQUE INDEX uk_users_email_normalized ON public.users (lower(email));

CREATE TABLE public.app_launches (
    launch_id UUID PRIMARY KEY,
    opened_at TIMESTAMPTZ(3) NOT NULL
);
ALTER TABLE public.app_launches ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.app_open_events (
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    launch_id UUID NOT NULL,
    opened_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (user_id, launch_id)
);

ALTER TABLE public.app_open_events ENABLE ROW LEVEL SECURITY;

CREATE TABLE public.auth_sessions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT NOT NULL,
    token_hash      VARCHAR(255) NOT NULL,
    ip_address      VARCHAR(45),
    device_info     VARCHAR(500),
    logged_in_at    TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    expires_at      TIMESTAMPTZ(3) NOT NULL,
    logged_out_at   TIMESTAMPTZ(3),

    CONSTRAINT pk_auth_sessions PRIMARY KEY (id),
    CONSTRAINT uk_auth_sessions_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_auth_sessions_expiry CHECK (expires_at > logged_in_at),
    CONSTRAINT fk_auth_sessions_user
        FOREIGN KEY (user_id) REFERENCES public.users (id)
        ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX idx_auth_sessions_user_active
    ON public.auth_sessions (user_id, logged_out_at, expires_at);

CREATE TABLE public.friendships (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    requester_id    BIGINT NOT NULL,
    addressee_id    BIGINT NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    responded_at    TIMESTAMPTZ(3),
    user_a_id       BIGINT GENERATED ALWAYS AS
                        (LEAST(requester_id, addressee_id)) STORED,
    user_b_id       BIGINT GENERATED ALWAYS AS
                        (GREATEST(requester_id, addressee_id)) STORED,

    CONSTRAINT pk_friendships PRIMARY KEY (id),
    CONSTRAINT uk_friendships_pair UNIQUE (user_a_id, user_b_id),
    CONSTRAINT ck_friendships_distinct_users CHECK (requester_id <> addressee_id),
    CONSTRAINT ck_friendships_status
        CHECK (status IN ('PENDING', 'ACCEPTED', 'BLOCKED')),
    CONSTRAINT ck_friendships_response
        CHECK (
            (status = 'PENDING' AND responded_at IS NULL)
            OR (status <> 'PENDING' AND responded_at IS NOT NULL)
        ),
    CONSTRAINT fk_friendships_requester
        FOREIGN KEY (requester_id) REFERENCES public.users (id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_friendships_addressee
        FOREIGN KEY (addressee_id) REFERENCES public.users (id)
        ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX idx_friendships_requester_status
    ON public.friendships (requester_id, status);
CREATE INDEX idx_friendships_addressee_status
    ON public.friendships (addressee_id, status);

CREATE TABLE public.conversations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    type            VARCHAR(20) NOT NULL,
    created_by      BIGINT,
    created_at      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    CONSTRAINT pk_conversations PRIMARY KEY (id),
    CONSTRAINT ck_conversations_type CHECK (type IN ('DIRECT', 'GROUP')),
    CONSTRAINT fk_conversations_creator
        FOREIGN KEY (created_by) REFERENCES public.users (id)
        ON UPDATE CASCADE ON DELETE SET NULL
);
CREATE INDEX idx_conversations_type_updated
    ON public.conversations (type, updated_at);

CREATE TABLE public.conversation_members (
    conversation_id BIGINT NOT NULL,
    user_id         BIGINT NOT NULL,
    member_role     VARCHAR(20) NOT NULL DEFAULT 'MEMBER',
    joined_at       TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    left_at         TIMESTAMPTZ(3),
    last_read_at    TIMESTAMPTZ(3),

    CONSTRAINT pk_conversation_members PRIMARY KEY (conversation_id, user_id),
    CONSTRAINT ck_conversation_members_role
        CHECK (member_role IN ('MEMBER', 'ADMIN', 'OWNER')),
    CONSTRAINT ck_conversation_members_left
        CHECK (left_at IS NULL OR left_at >= joined_at),
    CONSTRAINT fk_conversation_members_conversation
        FOREIGN KEY (conversation_id) REFERENCES public.conversations (id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_conversation_members_user
        FOREIGN KEY (user_id) REFERENCES public.users (id)
        ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX idx_conversation_members_user_active
    ON public.conversation_members (user_id, left_at, conversation_id);

CREATE TABLE public.group_details (
    conversation_id BIGINT NOT NULL,
    owner_id        BIGINT NOT NULL,
    name            VARCHAR(100) NOT NULL,
    avatar_url      VARCHAR(2048),
    description     TEXT,
    created_at      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    CONSTRAINT pk_group_details PRIMARY KEY (conversation_id),
    CONSTRAINT fk_group_details_conversation
        FOREIGN KEY (conversation_id) REFERENCES public.conversations (id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_group_details_owner
        FOREIGN KEY (owner_id) REFERENCES public.users (id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX idx_group_details_owner ON public.group_details (owner_id);

CREATE TABLE public.messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    conversation_id BIGINT NOT NULL,
    sender_id       BIGINT,
    reply_to_id     BIGINT,
    content         TEXT,
    message_type    VARCHAR(20) NOT NULL DEFAULT 'TEXT',
    status          VARCHAR(20) NOT NULL DEFAULT 'SENT',
    created_at      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    edited_at       TIMESTAMPTZ(3),

    CONSTRAINT pk_messages PRIMARY KEY (id),
    CONSTRAINT ck_messages_type
        CHECK (message_type IN ('TEXT', 'FILE', 'IMAGE', 'SYSTEM')),
    CONSTRAINT ck_messages_status
        CHECK (status IN ('SENT', 'EDITED', 'DELETED')),
    CONSTRAINT ck_messages_content
        CHECK (message_type <> 'TEXT' OR content IS NOT NULL),
    CONSTRAINT ck_messages_edited
        CHECK (
            (status = 'EDITED' AND edited_at IS NOT NULL)
            OR status <> 'EDITED'
        ),
    CONSTRAINT fk_messages_conversation
        FOREIGN KEY (conversation_id) REFERENCES public.conversations (id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_messages_sender
        FOREIGN KEY (sender_id) REFERENCES public.users (id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_messages_reply
        FOREIGN KEY (reply_to_id) REFERENCES public.messages (id)
        ON UPDATE CASCADE ON DELETE SET NULL
);
CREATE INDEX idx_messages_conversation_time
    ON public.messages (conversation_id, created_at, id);
CREATE INDEX idx_messages_sender_time ON public.messages (sender_id, created_at);
CREATE INDEX idx_messages_reply ON public.messages (reply_to_id);

CREATE TABLE public.message_attachments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    message_id      BIGINT NOT NULL,
    file_name       VARCHAR(255) NOT NULL,
    file_url        VARCHAR(2048) NOT NULL,
    mime_type       VARCHAR(255) NOT NULL,
    file_size       BIGINT NOT NULL,

    CONSTRAINT pk_message_attachments PRIMARY KEY (id),
    CONSTRAINT ck_message_attachments_size CHECK (file_size > 0),
    CONSTRAINT fk_message_attachments_message
        FOREIGN KEY (message_id) REFERENCES public.messages (id)
        ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX idx_message_attachments_message
    ON public.message_attachments (message_id);

CREATE TABLE public.message_reads (
    message_id      BIGINT NOT NULL,
    user_id         BIGINT NOT NULL,
    read_at         TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    CONSTRAINT pk_message_reads PRIMARY KEY (message_id, user_id),
    CONSTRAINT fk_message_reads_message
        FOREIGN KEY (message_id) REFERENCES public.messages (id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_message_reads_user
        FOREIGN KEY (user_id) REFERENCES public.users (id)
        ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX idx_message_reads_user_time ON public.message_reads (user_id, read_at);

CREATE TABLE public.reports (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reporter_id     BIGINT NOT NULL,
    message_id      BIGINT NOT NULL,
    reason          VARCHAR(50) NOT NULL,
    details         TEXT,
    status          VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    reviewed_by     BIGINT,
    created_at      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    reviewed_at     TIMESTAMPTZ(3),

    CONSTRAINT pk_reports PRIMARY KEY (id),
    CONSTRAINT uk_reports_reporter_message UNIQUE (reporter_id, message_id),
    CONSTRAINT ck_reports_status
        CHECK (status IN ('PENDING', 'REVIEWED', 'DISMISSED')),
    CONSTRAINT ck_reports_review
        CHECK (
            (status = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL)
            OR (status <> 'PENDING' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
        ),
    CONSTRAINT fk_reports_reporter
        FOREIGN KEY (reporter_id) REFERENCES public.users (id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_reports_message
        FOREIGN KEY (message_id) REFERENCES public.messages (id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_reports_reviewer
        FOREIGN KEY (reviewed_by) REFERENCES public.users (id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX idx_reports_status_created ON public.reports (status, created_at);
CREATE INDEX idx_reports_message ON public.reports (message_id);
CREATE INDEX idx_reports_reviewer ON public.reports (reviewed_by);

CREATE TABLE public.ai_requests (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT NOT NULL,
    conversation_id BIGINT,
    prompt          TEXT NOT NULL,
    response        TEXT,
    model           VARCHAR(100) NOT NULL,
    input_tokens    INTEGER NOT NULL DEFAULT 0,
    output_tokens   INTEGER NOT NULL DEFAULT 0,
    status          VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at      TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    CONSTRAINT pk_ai_requests PRIMARY KEY (id),
    CONSTRAINT ck_ai_requests_status
        CHECK (status IN ('PENDING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_ai_requests_input_tokens CHECK (input_tokens >= 0),
    CONSTRAINT ck_ai_requests_output_tokens CHECK (output_tokens >= 0),
    CONSTRAINT fk_ai_requests_user
        FOREIGN KEY (user_id) REFERENCES public.users (id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_ai_requests_conversation
        FOREIGN KEY (conversation_id) REFERENCES public.conversations (id)
        ON UPDATE CASCADE ON DELETE SET NULL
);
CREATE INDEX idx_ai_requests_user_time ON public.ai_requests (user_id, created_at);
CREATE INDEX idx_ai_requests_conversation_time
    ON public.ai_requests (conversation_id, created_at);
CREATE INDEX idx_ai_requests_status_time ON public.ai_requests (status, created_at);

-- PostgreSQL has no MySQL-style ON UPDATE timestamp column clause.
CREATE FUNCTION public.set_chat_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP(3);
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON public.users
    FOR EACH ROW EXECUTE FUNCTION public.set_chat_updated_at();

CREATE TRIGGER trg_conversations_updated_at
    BEFORE UPDATE ON public.conversations
    FOR EACH ROW EXECUTE FUNCTION public.set_chat_updated_at();

-- No Data API policies are defined: client-side anon/authenticated roles
-- cannot read or change application data. The trusted JDBC backend connects
-- with a privileged database role and must enforce user-level permissions.
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.auth_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.friendships ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.conversation_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.group_details ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.message_attachments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.message_reads ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ai_requests ENABLE ROW LEVEL SECURITY;

COMMIT;
